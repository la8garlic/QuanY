export type Message = keyof typeof english;
export type Language = "zh-CN" | "en";
const key = "interface-language";
const changes = new EventTarget();
function readLanguage(): Language {
  const saved = localStorage.getItem(key);
  if (saved === "zh-CN" || saved === "en") return saved;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}
export let locale = readLanguage();
export function t(message: Message): string {
  return locale === "en" ? english[message] : message;
}
function refreshLanguage() {
  locale = readLanguage();
  document.documentElement.lang = locale;
  document.title = document.body.classList.contains("memo-window")
    ? t("泉涌") + " · " + t("置顶便笺") : t("泉涌");
  changes.dispatchEvent(new Event("change"));
}
export function setLanguage(language: Language) {
  localStorage.setItem(key, language);
  refreshLanguage();
}
export function onLanguageChange(render: () => void) {
  changes.addEventListener("change", render);
  return () => changes.removeEventListener("change", render);
}
export function useLanguage() {
  return useSyncExternalStore(onLanguageChange, () => locale);
}
// WebView2 shares local storage between the desk and sticky notes.
window.addEventListener("storage", event => {
  if (event.key === key || event.key === null) refreshLanguage();
});
refreshLanguage();
